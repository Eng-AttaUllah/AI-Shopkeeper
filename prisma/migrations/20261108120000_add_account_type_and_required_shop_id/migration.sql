-- Phase 13 unit 13.4: make shopId required on every business table, replace
-- User.role with User.accountType, move User.customerId into
-- ShopMembership.customerId, and add per-shop composite uniques.
--
-- SQLite does not support ALTER COLUMN or dropping a column, so every affected
-- table is rebuilt. foreign_keys is deferred so the rebuild order does not
-- matter, and every business row already carries a shopId from the previous
-- migration (20261108093612), so NOT NULL is safe.
--
-- This migration is a no-op on a fresh database: the CREATE TABLE statements
-- in the initial migration will be regenerated by Prisma from the schema, and
-- this migration only mutates existing tables. Prisma migrate deploy applies it
-- on top of the current schema.

PRAGMA defer_foreign_keys=ON;
PRAGMA foreign_keys=OFF;

-- ---- users: role -> accountType, drop customerId ----
DROP TABLE IF EXISTS "users_new";

CREATE TABLE "users_new" (
    "id" TEXT NOT NULL PRIMARY KEY,
    "username" TEXT NOT NULL,
    "name" TEXT,
    "passwordHash" TEXT NOT NULL,
    "accountType" TEXT NOT NULL DEFAULT 'SHOPKEEPER',
    "tokenVersion" INTEGER NOT NULL DEFAULT 0,
    "createdAt" DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" DATETIME NOT NULL
);

INSERT INTO "users_new" ("id", "username", "name", "passwordHash", "accountType", "tokenVersion", "createdAt", "updatedAt")
SELECT "id", "username", "name", "passwordHash",
  CASE WHEN "role" = 'CUSTOMER' THEN 'CUSTOMER' ELSE 'SHOPKEEPER' END,
  "tokenVersion", "createdAt", "updatedAt" FROM "users";

DROP TABLE "users";
ALTER TABLE "users_new" RENAME TO "users";
CREATE UNIQUE INDEX "users_username_key" ON "users"("username");

